export function explainProblem(value, browser = 'Chrome') {
  const message = String(value || '').trim();
  if (!message) return '';
  for (const [pattern, instruction] of rules) if (pattern.test(message)) return instruction.replaceAll('{browser}', browser);
  if (/请|先|点击|选择|填写|复制|等待/.test(message) && !/HTTP|API|usage|JSON|iframe|scope|sourceId|原生|接口|预留|账本|异常|失败|错误|未知|\.mjs|Error|\/Users\//i.test(message)) return message;
  return '操作未完成，请重试。仍有问题时，在设置中导出诊断包。';
}

export function activityMessage(value, browser = 'Chrome') {
  const message = String(value || '').replace(/^\d{1,2}:\d{2}:\d{2}(?:\s*[AP]M)?\s*/i, '');
  if (/私有账本|API Key|截图|预览|原浏览器|所选浏览器的已有|控制器已断开/.test(message)) return '';
  if (/—|错误|失败|未知|超时|暂停.*原因|已自动(?:重试|补跑)|答案无法唯一匹配选项文本|AI选项序号无效/.test(message)) return explainProblem(message.split(' — ').at(-1), browser);
  const progress = message.match(/^(读取课程目录|播放视频|准备答案|等待网站验证|提交测验|已暂停|已完成) 已读任务 \d+\/\d+(?:（[^）]*）)?\s*(.*)$/);
  if (progress) return ({读取课程目录:'正在读取课程。',播放视频:'正在播放：'+progress[2],准备答案:'正在准备答案。',等待网站验证:'请点「去验证」，完成课程页面上的验证后保持页面打开。',提交测验:'正在提交测验，请保持课程页打开。',已暂停:'学习已暂停，点「继续」可以接着学。',已完成:'网站已确认当前课程内容完成，可以开始下一门。'})[progress[1]];
  if (/后续任务已停止/.test(message)) return '已停止学习，正在核对费用。';
  if (/平台目录已确认/.test(message)) return '网站已确认当前课程内容完成，可以开始下一门。';
  if (/已点击原生验证/.test(message)) return '正在等待课程网站确认验证结果，请保持课程页面打开。';
  if (/开始连接|课程浏览器已就绪/.test(message)) return '正在打开课程，请稍等。';
  if (/已选择.*请重新连接/.test(message)) return '已切换到 '+browser+'，请按页面指引连接并重新读取课程。';
  if (/解题服务设置已保存|已添加课程|签到设置已保存|运行环境已准备好|课程连接已结束/.test(message)) return ({'解题服务设置已保存。':'设置已保存，可以回到课程点「开始」或「继续」。','已添加课程。':'课程已加入列表，可以点「开始」。','签到设置已保存。':'签到设置已保存，请到课程网站核对签到结果。'})[message] || '操作已完成。';
  return '';
}

export function serviceActionFor(value) {
  const message = String(value || '');
  if (/EACCES|EPERM|ENOSPC|EROFS|EISDIR|ENOTDIR|检测记录.*无法读取|磁盘空间|目录权限|账本|费用记录.*(?:不可读|异常|无效)/.test(message)) return 'retry';
  if (/余额|额度|繁忙|限流|用量上限|欠费|AccountOverdue|SetLimitExceeded/.test(message)) return 'retry';
  if (/未开通|模型 ID|ModelNotOpen|模型暂不可用|文字答案|答案格式|本次检测.*(?:上限|预算)|检测.*调用上限/.test(message)) return 'model';
  if (/Key|401|403|鉴权|认证/.test(message)) return 'key';
  return 'url';
}
